#!/usr/bin/env node
/**
 * Writes src/tokenops/review-dates.json: the "Last reviewed" date shown on every pricing and
 * model page.
 *
 *   npm run review-dates            # rewrite the file from git history
 *   npm run review-dates -- --check # exit 1 if the committed file is out of date
 *
 * A page's date is the last commit that changed the source its figures come from — the
 * dataset, the briefing's markdown, or (for the dashboard) the sample-data lines — never the
 * route file around it, so restyling a page does not make it look freshly reviewed. Needs the
 * full git history: in a shallow clone every date would read as the clone's oldest commit, so
 * the script refuses to run there. Lovable builds from the committed file, never from git.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const ROOT = new URL("../", import.meta.url);
const OUT = "src/tokenops/review-dates.json";
const check = process.argv.includes("--check");

const git = (...args) => execFileSync("git", args, { cwd: ROOT, encoding: "utf8" }).trim();

if (git("rev-parse", "--is-shallow-repository") === "true") {
  console.error("Shallow clone: run `git fetch --unshallow` first, or the dates will be wrong.");
  process.exit(1);
}

/** Last commit date (YYYY-MM-DD) that touched a whole file. */
function fileDate(file) {
  const date = git("log", "-1", "--format=%cs", "--", file);
  if (!date) throw new Error(`${file} has no git history`);
  return date;
}

/** Latest commit date among the lines from `from` up to (not including) `to`. */
function linesDate(file, from, to) {
  const lines = readFileSync(new URL(file, ROOT), "utf8").split("\n");
  const start = lines.findIndex((line) => from.test(line));
  const end = lines.findIndex((line, i) => i > start && to.test(line));
  if (start < 0 || end < 0) throw new Error(`${file}: markers ${from} … ${to} not found`);
  const blame = git("blame", "--porcelain", "-L", `${start + 1},${end}`, "--", file);
  const times = [...blame.matchAll(/^committer-time (\d+)$/gm)].map((m) => Number(m[1]));
  return new Date(Math.max(...times) * 1000).toISOString().slice(0, 10);
}

const content = JSON.parse(readFileSync(new URL("src/tokenops/content.json", ROOT), "utf8"));
const PRICING = "data/pricing.json";

/** Routes: key is the path, value the date of the source behind their prices or line-up. */
const routes = {
  "/models": fileDate("src/lib/model-comparison.ts"),
  "/calculator": fileDate(PRICING),
  "/hub": fileDate(PRICING),
  "/toolkit": fileDate(PRICING),
  // The sample model line-up and figures live inside the route file itself.
  "/dashboard": linesDate(
    "src/routes/dashboard.tsx",
    /^const teamData = \[/,
    /^export const Route/,
  ),
};

/** Reader pages: every Models briefing plus the pricing references, keyed by reader path. */
const libraryFiles = [
  ...content.library.filter((item) => item.category === "Models").map((item) => item.file),
  "trends/2026-pricing-landscape.md",
  "references/provider-comparison-matrix.md",
];
const templateFiles = ["token-pricing-reference.md", "model-selection-matrix.md"];

const reader = Object.fromEntries([
  ...libraryFiles.map((file) => [`library/${file}`, fileDate(`public/library/${file}`)]),
  ...templateFiles.map((file) => [`template/${file}`, fileDate(`public/templates/${file}`)]),
]);

const next = `${JSON.stringify(
  {
    $comment:
      "Generated by scripts/gen-review-dates.mjs from git history (npm run review-dates). Do not hand-edit.",
    pages: { ...routes, ...reader },
  },
  null,
  2,
)}\n`;

if (check) {
  let current = "";
  try {
    current = readFileSync(new URL(OUT, ROOT), "utf8");
  } catch {
    /* missing counts as stale */
  }
  if (current !== next) {
    console.error(`${OUT} is out of date: run npm run review-dates and commit it.`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date.`);
} else {
  writeFileSync(new URL(OUT, ROOT), next);
  console.log(`Wrote ${OUT} (${Object.keys(routes).length + Object.keys(reader).length} pages).`);
}
